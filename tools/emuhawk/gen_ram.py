"""Turns the disassembly's ram.inc into ram.lua: name -> address of the 68000 RAM ($FF0000..)."""
import re, sys
src = sys.argv[1] if len(sys.argv) > 1 else r'D:\Git\Landstalker\landstalker_disasm\code\include\ram.inc'
out = []
for line in open(src, encoding='latin-1'):
    m = re.match(r'^(\w+):\s+equ\s+\$([0-9A-Fa-f]+)', line)
    if m and int(m.group(2), 16) >= 0xFF0000:
        out.append(f'  {m.group(1)} = 0x{int(m.group(2), 16):06X},')
open(__file__.replace('gen_ram.py', 'ram.lua'), 'w').write('-- generated by gen_ram.py from the disassembly (ram.inc)\nreturn {\n' + '\n'.join(out) + '\n}\n')
print(len(out), 'symbols')
